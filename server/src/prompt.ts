/** Подсказка с актуальной копилкой приёмов — собирается на каждый ход. */
export function systemPrompt(): string {
  const recipes = recipesForPrompt()
  return recipes ? `${SYSTEM_PROMPT}\n\n${recipes}` : SYSTEM_PROMPT
}

/** Текст для AGENTS.md в рабочем каталоге Codex — тот же промпт. */
export function agentsMd(): string {
  return `# Stultus\n\n${systemPrompt()}\n`
}
